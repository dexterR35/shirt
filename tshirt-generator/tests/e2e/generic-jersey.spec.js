import { test, expect } from '@playwright/test';
import sharp from 'sharp';
import fs from 'node:fs/promises';

test.use({ baseURL: `http://127.0.0.1:${process.env.E2E_PORT || 5173}` });

test('the default shirt is the green N design, with shared controls and image download', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1050 });
  await page.goto('/studio');
  const shirt = page.locator('.shirt-image');
  await expect(shirt).toHaveAttribute('aria-label', 'Generic jersey on-dark');
  await expect(page.getByRole('button', { name: 'Generic jersey', exact: true })).toHaveCount(0);
  await expect(page.getByText('DEFAULT DESIGN', { exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'For light backgrounds', exact: true })).toHaveCount(0);
  await expect(shirt).toHaveAttribute('data-render-state', 'ready');
  const dark = await shirt.evaluate(c => c.toDataURL());
  await page.getByRole('button', { name: 'White background', exact: true }).click();
  expect(await shirt.evaluate(c => c.toDataURL())).toBe(dark);
  await expect(page.locator('.canvas')).toHaveClass(/white/);
  await page.reload();
  await expect(shirt).toHaveAttribute('aria-label', 'Generic jersey on-dark');
  await expect(shirt).toHaveAttribute('data-render-state', 'ready');
  await expect(page.locator('.team-row').first()).toContainText('Default shirt');
  await expect(page.getByRole('button', { name: 'Download', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Add to collection', exact: true }).click();
  await page.getByLabel('Download size').selectOption('168');
  await page.getByLabel('Download format').selectOption('png');
  await page.getByRole('button', { name: 'Download all', exact: true }).click();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Yes, download' }).click();
  const download = await downloadPromise;
  expect(download.suggestedFilename()).toBe('jersey-generic-on-dark-r005-168x168.png');
  const pixels = await sharp(await download.path()).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  expect(pixels.info.width).toBe(168);
  expect(pixels.info.height).toBe(168);
  expect(pixels.data[3]).toBe(0);
  expect(pixels.data[(84 * 168 + 84) * 4 + 3]).toBe(255);
  await expect(shirt).toHaveAttribute('data-render-state', 'ready');
  await page.screenshot({ path: 'artifacts/generic-jersey/r005/studio-preview.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByLabel('Team', { exact: true }).fill('Arsenal');
  await page.getByRole('button', { name: /Arsenal England/ }).click();
  await expect(shirt).toHaveAttribute('aria-label', 'Arsenal home shirt');
  await expect(shirt).toHaveAttribute('data-render-state', 'ready');
  await expect(page.getByRole('button', { name: 'Add to collection', exact: true })).toBeEnabled();
  await expect(page.getByRole('region', { name: 'Generic jersey details' })).toHaveCount(0);
  await page.reload();
  await expect(shirt).toHaveAttribute('aria-label', 'Arsenal home shirt');
  await expect(shirt).toHaveAttribute('data-render-state', 'ready');
  await page.getByRole('button', { name: 'Clear team', exact: true }).click();
  await expect(shirt).toHaveAttribute('aria-label', 'Generic jersey on-dark');
  await expect(shirt).toHaveAttribute('data-render-state', 'ready');
  expect(await shirt.evaluate(c => c.toDataURL())).toBe(dark);
});

test('default N can be edited, saved as JSON, revisited and reset without replacing its source', async ({page}) => {
  await page.goto('/studio');
  const shirt=page.locator('.shirt-image');
  await expect(shirt).toHaveAttribute('data-render-state','ready');
  const original=await shirt.evaluate(canvas=>canvas.toDataURL());
  await page.getByRole('button',{name:'Edit',exact:true}).click();
  await page.getByRole('button',{name:'N motif',exact:true}).click();
  await page.getByLabel('N motif color',{exact:true}).fill('#22cc88');
  await page.getByRole('button',{name:'Save',exact:true}).click();
  await expect.poll(()=>shirt.evaluate(canvas=>canvas.toDataURL())).not.toBe(original);
  const jsonPromise=page.waitForEvent('download');
  await page.getByRole('button',{name:'Add to collection',exact:true}).click();
  await page.getByRole('button',{name:'Download design JSON',exact:true}).click();
  const download=await jsonPromise;
  expect(download.suggestedFilename()).toBe('jersey-generic-on-dark-r005-custom.json');
  const document=JSON.parse(await fs.readFile(await download.path(),'utf8'));
  expect(document.custom).toBe(true);
  expect(document.config.layers.find(layer=>layer.id==='rounded-n-motif').fill).toBe('#22CC88');
  expect(document.config.colors.leftSleeve).toBe('#13AE8E');

  await page.getByLabel('Team',{exact:true}).fill('Arsenal');
  await page.getByRole('button',{name:/Arsenal England/}).click();
  await expect(shirt).toHaveAttribute('aria-label','Arsenal home shirt');
  await expect(shirt).toHaveAttribute('data-render-state','ready');
  await page.getByRole('button',{name:'Clear team',exact:true}).click();
  await page.getByRole('button',{name:'Edit',exact:true}).click();
  await page.getByRole('button',{name:/^N motif/}).click();
  await expect(page.getByLabel('N motif color',{exact:true})).toHaveValue('#22cc88');
  await page.getByRole('button',{name:'Reset all',exact:true}).click();
  await page.getByRole('button',{name:'Save',exact:true}).click();
  await expect.poll(()=>shirt.evaluate(canvas=>canvas.toDataURL())).toBe(original);
});


test('default and team shirts share collection ordering, navigation and ZIP export', async ({page}) => {
  await page.setViewportSize({width: 1440, height: 1050});
  await page.goto('/studio');
  await page.getByLabel('Team', {exact:true}).fill('Arsenal');
  await page.getByRole('button', {name:/Arsenal England/}).click();
  await expect(page.locator('.shirt-image')).toHaveAttribute('data-render-state','ready');
  await page.getByRole('button',{name:'Add to collection',exact:true}).click();
  const home = await page.getByRole('button',{name:'Home',exact:true}).boundingBox();
  const add = await page.getByRole('button',{name:'Add to collection',exact:true}).boundingBox();
  expect(Math.abs(home.y - add.y)).toBeLessThan(8);
  expect(add.x).toBeGreaterThan(home.x);
  await page.locator('.team-row').first().click();
  await page.getByRole('button',{name:'Add to collection',exact:true}).click();
  await expect(page.locator('.collection-item').first()).toContainText('Default shirt');
  await expect(page.locator('.collection-item')).toHaveCount(2);
  await page.getByRole('button',{name:'Add to collection',exact:true}).click();
  await expect(page.locator('.collection-item')).toHaveCount(2);
  await page.getByLabel('Download size',{exact:true}).selectOption('168');
  await page.getByRole('button',{name:'ZIP all',exact:true}).click();
  const pending=page.waitForEvent('download');
  await page.getByRole('button',{name:'Yes, download'}).click();
  const download=await pending;
  const {unzipSync}=await import('fflate');
  const files=unzipSync(await fs.readFile(await download.path()));
  expect(Object.keys(files).filter(name=>name.endsWith('.png'))).toHaveLength(2);
  expect(files['jersey-generic-on-dark-r005-168x168.png']).toBeTruthy();
  await page.locator('.collection-item').nth(1).locator('button').first().click();
  await expect(page.locator('.shirt-image')).toHaveAttribute('aria-label','Arsenal home shirt');
  await page.locator('.collection-item').first().locator('button').first().click();
  await expect(page.locator('.shirt-image')).toHaveAttribute('aria-label','Generic jersey on-dark');
  await page.screenshot({path:'artifacts/studio-collection-layout.png',fullPage:true});
});


test('SVG collection export preserves the PNG pixels and transparency', async ({page}) => {
  await page.goto('/studio');
  await page.getByRole('button',{name:'Add to collection',exact:true}).click();
  await page.getByLabel('Download size',{exact:true}).selectOption('168');
  await page.getByLabel('Download format',{exact:true}).selectOption('svg');
  await page.getByRole('button',{name:'Download all',exact:true}).click();
  await expect(page.getByText(/SVG contains the rendered PNG/)).toBeVisible();
  const pending=page.waitForEvent('download');
  await page.getByRole('button',{name:'Yes, download'}).click();
  const download=await pending;
  expect(download.suggestedFilename()).toBe('jersey-generic-on-dark-r005-168x168.svg');
  const svg=await fs.readFile(await download.path(),'utf8');
  expect(svg).toContain('viewBox="0 0 168 168"');
  const embedded=Buffer.from(svg.match(/base64,([^" ]+)/)[1],'base64');
  const pixels=await sharp(embedded).ensureAlpha().raw().toBuffer({resolveWithObject:true});
  expect(pixels.info.width).toBe(168);
  expect(pixels.data[3]).toBe(0);
  expect(pixels.data[(84*168+84)*4+3]).toBe(255);
});
