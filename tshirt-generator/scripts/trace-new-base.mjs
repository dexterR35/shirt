import fs from 'node:fs/promises';
import crypto from 'node:crypto';
import sharp from 'sharp';

// Trace source masks into closed, simplified vector contours. Photos are never
// embedded in the SVG. Work in the same 200-unit space as the kit artwork.
const source = 'base.png';
const bytes = await fs.readFile(source);
const hash = crypto.createHash('sha256').update(bytes).digest('hex');
const {data: original, info} = await sharp(bytes).ensureAlpha().raw().toBuffer({resolveWithObject:true});
let left=info.width, top=info.height, right=0, bottom=0;
for(let y=0;y<info.height;y++) for(let x=0;x<info.width;x++) {
  if(original[(y*info.width+x)*4+3] < 128) continue;
  left=Math.min(left,x); right=Math.max(right,x); top=Math.min(top,y); bottom=Math.max(bottom,y);
}
if(right<=left || bottom<=top) throw Error('Base has no opaque garment');
const size=600, height=588, width=Math.round((right-left+1)/(bottom-top+1)*height);
const offsetX=Math.floor((size-width)/2), offsetY=6;
const crop={left,top,width:right-left+1,height:bottom-top+1};
const normalized=await sharp(bytes).extract(crop).resize(width,height).extend({left:offsetX,right:size-width-offsetX,top:offsetY,bottom:size-height-offsetY,background:'#00000000'}).png().toBuffer();
await fs.mkdir('artifacts/new-base',{recursive:true});
await fs.writeFile('artifacts/new-base/source-normalized.png',normalized);
const {data}=await sharp(normalized).ensureAlpha().raw().toBuffer({resolveWithObject:true});
const blurred=await sharp(normalized).flatten({background:'#ffffff'}).blur(1.2).raw().toBuffer();

function simplify(points,tolerance) {
  if(points.length<3) return points;
  const [a,b]=[points[0],points.at(-1)]; let distance=0,index=0;
  for(let i=1;i<points.length-1;i++) {
    const p=points[i],dx=b[0]-a[0],dy=b[1]-a[1];
    const t=Math.max(0,Math.min(1,((p[0]-a[0])*dx+(p[1]-a[1])*dy)/(dx*dx+dy*dy||1)));
    const d=Math.hypot(p[0]-a[0]-t*dx,p[1]-a[1]-t*dy);
    if(d>distance){distance=d;index=i;}
  }
  return distance>tolerance ? [...simplify(points.slice(0,index+1),tolerance).slice(0,-1),...simplify(points.slice(index),tolerance)] : [a,b];
}
function contours(mask,minimumArea,tolerance,maxSegment=Infinity) {
  const edges=new Map(),stride=size+1;
  const add=(x,y,xx,yy)=> {const key=y*stride+x; const list=edges.get(key)||[];list.push(yy*stride+xx);edges.set(key,list);};
  const on=(x,y)=>x>=0&&y>=0&&x<size&&y<size&&mask[y*size+x];
  for(let y=0;y<size;y++) for(let x=0;x<size;x++) if(on(x,y)){
    if(!on(x,y-1))add(x,y,x+1,y);
    if(!on(x+1,y))add(x+1,y,x+1,y+1);
    if(!on(x,y+1))add(x+1,y+1,x,y+1);
    if(!on(x-1,y))add(x,y+1,x,y);
  }
  const result=[];
  while(edges.size){
    const start=edges.keys().next().value;let key=start,points=[];
    do {points.push([key%stride/3,Math.floor(key/stride)/3]);const next=edges.get(key);if(!next)throw Error('Open contour'); const dest=next.pop();if(!next.length)edges.delete(key);key=dest;}while(key!==start);
    const area=points.reduce((sum,p,i)=>{const q=points[(i+1)%points.length];return sum+p[0]*q[1]-q[0]*p[1];},0)/2;
    if(Math.abs(area)<minimumArea)continue;
    // Split the closed contour in two before RDP so coincident endpoints
    // cannot collapse a whole garment or a circular fold.
    const half=Math.floor(points.length/2);
    points=[...simplify(points.slice(0,half+1),tolerance).slice(0,-1),...simplify([...points.slice(half),points[0]],tolerance).slice(0,-1)];
    // Limit corner rounding on the exterior: midpoint smoothing must not
    // round an entire long sleeve edge into its adjoining shoulder segment.
    if(Number.isFinite(maxSegment)) points=points.flatMap((p,i)=>{
      const q=points[(i+1)%points.length],steps=Math.ceil(Math.hypot(q[0]-p[0],q[1]-p[1])/maxSegment);
      return Array.from({length:steps},(_,j)=>[p[0]+(q[0]-p[0])*j/steps,p[1]+(q[1]-p[1])*j/steps]);
    });
    const f=n=>Number(n.toFixed(3));
    const mid=(a,b)=>`${f((a[0]+b[0])/2)} ${f((a[1]+b[1])/2)}`;
    const d=`M${mid(points.at(-1),points[0])}`+points.map((p,i)=>`Q${f(p[0])} ${f(p[1])} ${mid(p,points[(i+1)%points.length])}`).join('')+'Z';
    result.push({d,area});
  }
  return result;
}
const support=Uint8Array.from({length:size*size},(_,i)=>data[i*4+3]>=128?1:0);
const outline=contours(support,10,.4,2).sort((a,b)=>Math.abs(b.area)-Math.abs(a.area))[0].d;
const shadows=[];
const shadeStep=2;
for(let darkness=shadeStep;darkness<=224;darkness+=shadeStep){
  const mask=Uint8Array.from(support,(on,i)=>on && 255-(blurred[i*3]*.2126+blurred[i*3+1]*.7152+blurred[i*3+2]*.0722)>=darkness ? 1:0);
  const paths=contours(mask,.35,.3);
  if(paths.length)shadows.push({opacity:Number((shadeStep/(255-darkness+shadeStep)).toFixed(6)),d:paths.map(p=>p.d).join('')});
}
await fs.writeFile('src/lib/generated/new-base-surface.js',`// Generated by scripts/trace-new-base.mjs from the replacement base.png.\n// Simplified quadratic contours, no embedded bitmap.\nexport const NEW_BASE_SHA256 = ${JSON.stringify(hash)};\nexport const NEW_BASE_OUTLINE = ${JSON.stringify(outline)};\nexport const NEW_BASE_SHADOWS = ${JSON.stringify(shadows)};\n`);
const svg=`<svg xmlns="http://www.w3.org/2000/svg" width="600" height="600" viewBox="0 0 200 200"><path fill="white" d="${outline}"/></svg>`;
const alpha=await sharp(Buffer.from(svg)).ensureAlpha().raw().toBuffer();
let union=0,intersection=0;
for(let i=0;i<support.length;i++){const a=support[i],b=alpha[i*4+3]>=128; if(a||b)union++;if(a&&b)intersection++;}
const report={source,sha256:hash,width:info.width,height:info.height,source_bounds:crop,coordinate_space:'reference-200',normalized_bounds:{x:offsetX/3,y:2,width:width/3,height:196},silhouette_iou:intersection/union,shadow_layers:shadows.length,method:'Alpha contour simplified to quadratic paths. Neutral luminance traced in 2/255 steps after light smoothing; textile microtexture omitted. Separate black vector shadow contours recolor with the garment.',copies:[]};
for(const path of ['starter/shirt-svg/base.png','starter/shirt-svg/png/base.png']){
  const sha256=crypto.createHash('sha256').update(await fs.readFile(path)).digest('hex');
  if(sha256!==hash)throw Error(`Replacement copy differs: ${path}`);
  report.copies.push({path,sha256});
}
await fs.writeFile('artifacts/new-base/analysis.json',JSON.stringify(report,null,2)+'\n');
